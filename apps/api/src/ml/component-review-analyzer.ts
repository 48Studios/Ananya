export const COMPONENT_REVIEW_INTELLIGENCE_VERSION = 'component-review-v1';

/** Minimum confidence for ML-derived (manufacturer/category) findings. */
export const REVIEW_MIN_CONFIDENCE = 0.85;

/** Shortest normalized part number considered a real identifier. */
export const MIN_MPN_LENGTH = 4;

