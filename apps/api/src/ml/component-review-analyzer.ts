/**
 * Component Intelligence Review Analyzer (Pass 2).
 *
 * Analyzes PERSISTED components and produces evidence-backed review findings
 * for `ComponentReviewQueueService.persistFindings()`.
 *
 * Core principle: the queue is not a firehose for every ML output. A finding is
 * only generated when there is a *meaningful discrepancy* a human should judge:
 *
 *  - the stored value is missing and analysis can supply one, or
 *  - the stored value disagrees with a high-confidence, evidence-backed
 *    conclusion, or
 *  - two persisted records appear to describe the same part.
 *
 * Rules intentionally NOT implemented here:
 *  - "no suggestion available" cases (nothing to review),
 *  - new-category candidates (creating taxonomies from a review queue is out of
 *    scope; category-attribute intelligence owns taxonomy curation),
 *  - attribute-level data quality (missing/conflicting component attribute
 *    values) which belongs to the following pass.
 *
 * Safety: the analyzer NEVER mutates component data. It only persists findings.
 */

/** Bumped when rule semantics change so fingerprints are re-evaluated. */
